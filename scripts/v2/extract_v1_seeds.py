"""One-off: turn v1's hard-coded knowledge into versioned v2 seed files.

v1 kept partners, risks, recommendation blueprints, signal rules and the topic
taxonomy as Python literals spread over a dozen modules. This script reads them
with ``ast`` (no v1 imports, so no torch/faiss needed) and writes ``seeds/*.yaml``
plus evaluation seeds. Re-run it only while v1 code still exists. After that the
YAML files are the source of truth and are edited directly.

    python scripts/v2/extract_v1_seeds.py
"""

from __future__ import annotations

import ast
import json
import re
from datetime import date
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[2]
SEEDS = ROOT / "seeds"
EVALS = ROOT / "evals" / "datasets"
VERSION = f"v1-import-{date.today().isoformat()}"


def literal(path: str, name: str) -> Any:
    tree = ast.parse((ROOT / path).read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id == name:
                    return ast.literal_eval(node.value)
    raise KeyError(f"{name} not found in {path}")


def dump(path: Path, header: str, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    body = yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=110)
    path.write_text(f"# {header}\n# Generated by scripts/v2/extract_v1_seeds.py from v1 code; edit freely.\n\n{body}",
                    encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")


def clean_keywords(words: list[str]) -> list[str]:
    seen: dict[str, None] = {}
    for w in words:
        w = w.strip().lower()
        if w:
            seen.setdefault(w, None)
    return list(seen)


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def main() -> None:
    router_topics = literal("app/agents/query_router.py", "TOPIC_RULES")
    cleaner_topics = literal("app/processing/cleaner.py", "topic_rules")
    topics: dict[str, list[str]] = {}
    for source in (router_topics, cleaner_topics):
        for topic, kws in source.items():
            topics[topic] = clean_keywords(topics.get(topic, []) + kws)

    impact_weights = literal("app/intelligence/scoring.py", "topic_weights")
    business_units = literal("app/intelligence/business_unit_strategy.py", "BUSINESS_UNITS")
    bu_rules = literal("app/agents/query_router.py", "BUSINESS_AREA_RULES")
    bu_keywords = {name: clean_keywords(kws) for name, kws in bu_rules.items()}
    for name, spec in business_units.items():
        if isinstance(spec, dict) and "keywords" in spec:
            bu_keywords[name] = clean_keywords(bu_keywords.get(name, []) + spec["keywords"])

    dump(SEEDS / "taxonomy.yaml", "Strategic taxonomy: topics, business units, regions, intents, constraints", {
        "version": VERSION,
        "ignore_phrases": [
            "airbus defence and space", "airbus defense and space", "defence and space", "defense and space",
            "aerospace",
        ],
        "topics": topics,
        "topic_impact_weights": impact_weights,
        "business_units": bu_keywords,
        # Topic -> business unit (v1 BUSINESS_UNITS). Umbrella units are used only when nothing specific fits.
        "business_unit_topics": {name: list(spec.get("topics", [])) for name, spec in business_units.items()
                                 if isinstance(spec, dict)},
        "umbrella_business_units": ["Airbus Defence and Space", "Airbus Corporate / Group Strategy"],
        "regions": {k: clean_keywords(v) for k, v in literal("app/agents/query_router.py", "REGION_RULES").items()},
        "intents": {k: clean_keywords(v) for k, v in literal("app/agents/query_router.py", "INTENT_RULES").items()},
        "constraints": {
            k: clean_keywords(v) for k, v in literal("app/agents/query_router.py", "CONSTRAINT_RULES").items()
        },
    })

    registry = literal("app/ingestion/source_registry.py", "SOURCES")
    trusted = literal("app/ingestion/collectors/rss_intelligence_collector.py", "TRUSTED_SOURCE_KEYWORDS")
    dump(SEEDS / "sources.yaml", "Sources, publisher credibility priors and collection plan", {
        "version": VERSION,
        "licence_review_required": True,
        # research_mode = store full text for non-commercial research (v1 behaviour);
        # respect_licence = full text only where licence allows (required before commercial use). ADR 0004.
        "full_text_policy": "research_mode",
        "notes": (
            "licence must be reviewed per source before production use (finding P3). "
            "'unknown' = store headline + link + short snippet only."
        ),
        "sources": [
            {
                "name": s["name"],
                "source_type": s["source_type"],
                "base_url": s["base_url"],
                "credibility_prior": s["trust_score"],
                "publisher_group": slug(s["name"].split()[0]),
                "licence": "unknown",
            }
            for s in registry
        ],
        # Feed items name their publisher; these priors are matched case-insensitively.
        "publisher_priors": {k: v for k, v in trusted.items()},
        # Exact publisher names (case-insensitive); take precedence over publisher_priors. Analyst-maintained.
        # Low values: content-farm / SEO-spam items found in the v1 corpus (2026-11-07 review).
        "publisher_overrides": {
            "Mshale": 0.05, "Fathom Journal": 0.05, "facebook.com": 0.2, "Moomoo": 0.3, "TradingView": 0.3,
            "Financial Times": 0.9, "DW.com": 0.85, "Euronews.com": 0.8, "SpaceNews": 0.84, "TWZ": 0.8,
        },
        "default_news_prior": 0.65,
        "collection": {
            "official_seed_urls": literal("app/ingestion/collectors/airbus_live_collector.py", "OFFICIAL_SEED_URLS"),
            "official_allowed_hosts": ["airbus.com"],
            "official_path_tokens": [
                "defence", "newsroom", "fcas", "eurofighter", "space", "uav", "military", "press-release",
            ],
            "news_queries": clean_keywords(
                literal("app/ingestion/collectors/airbus_live_collector.py", "NEWS_QUERIES")
                + literal("app/ingestion/collectors/rss_intelligence_collector.py", "AIRBUS_INTELLIGENCE_QUERIES")
            ),
            "news_feed_template": "https://news.google.com/rss/search?q={query}&hl=en-US&gl=US&ceid=US:en",
        },
    })

    partners = literal("app/agents/ceo_chat_agent.py", "PARTNER_CAPABILITY_MAP")
    dump(SEEDS / "partners.yaml", "Partner registry (analyst-maintained; v1 PARTNER_CAPABILITY_MAP)", {
        "version": VERSION,
        "partners": [
            {
                "name": name,
                "aliases": [name],
                "country": info["country"],
                "capabilities": [c.strip() for c in info["capability"].split(",")],
                "collaboration_areas": [c.strip() for c in info["collaboration_area"].split(",")],
                "known_risks": [r.strip() for r in info["risk"].split(",")],
                "provenance": "v1 hard-coded map; needs evidence links",
            }
            for name, info in partners.items()
        ],
    })

    dump(SEEDS / "risk_checklist.yaml", "Risk checklist per topic and decision-option framing", {
        "version": VERSION,
        "risks": literal("app/agents/ceo_chat_agent.py", "RISK_LIBRARY"),
        "decision_options": literal("app/agents/ceo_chat_agent.py", "OPTION_LIBRARY"),
    })

    blueprints = literal("app/agents/ceo_recommendation_engine.py", "RECOMMENDATION_BLUEPRINTS")
    dump(SEEDS / "recommendations_v1.yaml", "v1 recommendation blueprints, imported as version 1", {
        "version": VERSION,
        "status_on_import": "draft",
        "notes": ("Hand-written in v1 without verified evidence (finding B8). Imported as drafts with candidate "
                  "evidence auto-linked; a named reviewer approves them (needs 2+ independent publishers)."),
        "recommendations": [{"key": slug(b["title"])[:60], **b} for b in blueprints],
    })

    dump(SEEDS / "drilldown_prompts.yaml", "Drill-down actions -> MCP prompts on strategy-mcp", {
        "version": VERSION,
        "prompts": [
            {"name": slug(title), "title": title, "instruction": text}
            for title, text in literal("app/agents/recommendation_drilldown.py", "DRILLDOWN_ACTIONS").items()
        ],
    })

    dump(SEEDS / "signal_rules_v1.yaml", "v1 keyword signal rules: kept as the rule-based fallback extractor", {
        "version": VERSION,
        "extractor_id": "rule:v1",
        "opportunity": literal("app/intelligence/signal_extractor.py", "OPPORTUNITY_RULES"),
        "risk": literal("app/intelligence/signal_extractor.py", "RISK_RULES"),
        "trend": literal("app/intelligence/signal_extractor.py", "TREND_RULES"),
    })

    EVALS.mkdir(parents=True, exist_ok=True)
    seed_sh = (ROOT / "scripts/seed_ceo_questions.sh").read_text(encoding="utf-8")
    questions = literal("app/dashboard/demo_control.py", "DEMO_QUESTIONS")
    questions += re.findall(r'ask_ceo\.sh "([^"]+)"', seed_sh)
    unique_q = list(dict.fromkeys(questions))
    with (EVALS / "golden_questions_seed.jsonl").open("w", encoding="utf-8") as fh:
        for i, q in enumerate(unique_q, 1):
            fh.write(json.dumps({"qid": f"gq{i:03d}", "question": q, "key_points": [], "required_sources": [],
                                 "acceptable_tool_paths": [], "status": "needs_labels"}) + "\n")
    print(f"wrote evals/datasets/golden_questions_seed.jsonl ({len(unique_q)} questions)")

    probes = literal("app/evaluation/evaluation_suite.py", "RETRIEVAL_PROBES")
    with (EVALS / "retrieval_queries_seed.jsonl").open("w", encoding="utf-8") as fh:
        for i, p in enumerate(probes, 1):
            fh.write(json.dumps({"qid": f"rq{i:03d}", "query": p["query"], "v1_expected_terms": p["expected_terms"]})
                     + "\n")
        for i, q in enumerate(unique_q, len(probes) + 1):
            fh.write(json.dumps({"qid": f"rq{i:03d}", "query": q}) + "\n")
    print("wrote evals/datasets/retrieval_queries_seed.jsonl")


if __name__ == "__main__":
    main()
